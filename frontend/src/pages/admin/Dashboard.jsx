export default function Dashboard() {
  const [stats, setStats]     = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError]     = useState(null);

  useEffect(() => {
    adminApi.getStats()
      .then((data) => { setStats(data); setError(null); })
      .catch(() => setError('Failed to load statistics'))
      .finally(() => setLoading(false));
  }, []);

  return (
    <AdminPage title="Dashboard" loading={loading} error={error}>
      <PageCard className="p-6 mb-6">
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-6">
          <StatCard title="Total Users"        value={stats?.users ?? 0}               icon={IconUsers}     color="blue"   />
          <StatCard title="Total Jobs"         value={stats?.jobs ?? 0}                icon={IconBriefcase} color="green"  />
          <StatCard title="Total Companies"    value={stats?.companies ?? 0}           icon={IconBuilding}  color="purple" />
          <StatCard title="Total Applications" value={stats?.applications?.total ?? 0} icon={IconClipboard} color="yellow" />
        </div>
      </PageCard>

      <PageCard className="p-6">
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-6">
          <StatCard title="Pending"  value={stats?.applications?.pending ?? 0}  icon={IconClock}       color="yellow" />
          <StatCard title="Reviewed" value={stats?.applications?.reviewed ?? 0} icon={IconEye}         color="blue"   />
          <StatCard title="Accepted" value={stats?.applications?.accepted ?? 0} icon={IconCheckCircle} color="green"  />
          <StatCard title="Rejected" value={stats?.applications?.rejected ?? 0} icon={IconXCircle}     color="red"    />
        </div>
      </PageCard>
    </AdminPage>
  );
}
